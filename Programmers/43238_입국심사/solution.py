# 프로그래머스 43238 입국심사 (Lv3)
#
# 문제: n명을 심사관들이 나눠 심사할 때, 모두 끝나는 최소 시간
# 제한: n <= 1,000,000,000, 심사 시간 <= 1,000,000,000, 심사관 <= 100,000
#
# 판단: 한 명씩 배정하는 시뮬레이션은 10억 번 -> 불가
#       "T분이면 n명 가능한가?"는 sum(T // t)로 바로 계산 가능
#       T가 가능하면 T+1도 가능 -> 경계를 이분 탐색 (파라메트릭 서치)
#
# 시간 복잡도: O(M log(min(times) * n)), M = 심사관 수

def solution(n, times):
    # 최소를 1분으로 두고 최대를 빠른 심사관이 혼자 심사하는 시간
    lo, hi = 1, min(times) * n
    # 가장 빠른 심사관이 혼자하는 것이 가능하기에 일단 초기값으로 설정
    answer = hi

    # 이분탐색 시작
    while lo <= hi:
        # mid를 기준으로 심사관들이 n명을 심사할 수 있는지 확인
        mid = (lo + hi) // 2
        # mid 시간동안 심사관들이 심사할 수 있는 인원수 계산
        total = sum(mid // t for t in times)
        # mid 시간동안 심사관들이 심사한 수가 입국 심사를 받을 사람보다 많거나 적은지 확인
        if total >= n:
            # 많거나 같은 경우 더 짧은 시간동안 심사할 수 있는지 확인하기 위해 hi를 mid - 1로 설정
            answer = mid
            hi = mid - 1
        else:
            # 적은 경우 더 긴 시간동안 심사를 진행해야 하므로 lo를 mid + 1로 설정
            lo = mid + 1
    return answer