# 문제: 병사 n명, 무적권 k장으로 최대 몇 라운드를 막을 수 있는지
# 제한: enemy 길이 <= 1,000,000, k <= 500,000
#
# 판단: 라운드마다 무적권 사용 여부 -> 부분집합처럼 보이지만 2^1,000,000 -> 완전 탐색 불가
#       무적권은 적이 가장 많은 라운드에 쓰는 것이 최선 -> 그리디
#       지금까지 무적권을 쓴 라운드 중 최솟값을 빠르게 꺼내야 함 -> 최소 힙
#
# 시간 복잡도: O(N log k)

import heapq

def solution(n, k, enemy):
    #최소 힙을 사용하여 가장 작은 적의 수를 제거하고, 남은 적의 수가 n보다 작으면 다음 라운드로 진행
    heap = []

    for i in range(len(enemy)):
        #이번 라운드는 무적권으로 처리했다고 가정하고 적을 수를 힙에 넣기
        heapq.heappush(heap, enemy[i])
        #힙의 크기가 k보다 크면 가장 적은 적의 수를 제거하고, 남의 적의 수가 n보다 작으면 다음 라운드로 진행
        if len(heap) > k:
            #무적권으로 막은 라운드 중 가장 적이 적은 라운드의 적을 제거하고 병사 수 감소
            n -= heapq.heappop(heap)
            #만약 남은 병사 수가 0보다 작으면 현재 라운드 반환
            if n < 0:
                return i

    #모든 라운드를 성공하면 전체 라운드 길이 반환
    return len(enemy)